"""Catalogo stringhe it/en, rilevamento lingua e funzione T().

Regole:
- `T(key)` rende la stringa nella lingua corrente, con fallback all'italiano.
- Le stringhe valutate all'import (BINDINGS, MENU_IT) seguono la lingua
  impostata PRIMA della definizione delle classi (vedi _apply_startup_lang).
- Le stringhe valutate a runtime (compose, notify, system commands) seguono
  sempre la lingua corrente.
"""

import locale

LANGS = ("it", "en")

_current = "it"


def detect_system_lang() -> str:
    """'it' se il sistema e' italiano, altrimenti 'en'.

    Se il locale e' indeterminato (C/POSIX/vuoto) ritorna 'it'
    per non cambiare lingua agli utenti esistenti.
    """
    import os

    try:
        loc = locale.getlocale()[0] or ""
    except Exception:
        loc = ""
    env = " ".join(
        x
        for x in (
            loc,
            os.environ.get("LC_ALL", ""),
            os.environ.get("LANG", ""),
        )
        if x
    )
    if not env or env.upper().startswith(("C.", "C ", "POSIX")):
        return "it"
    low = env.lower()
    if "italian" in low or low.startswith("it") or "_it" in low:
        return "it"
    return "en"


def set_lang(code: str) -> str:
    """Imposta la lingua corrente ('it'/'en'), ritorna quella effettiva."""
    global _current
    _current = "it" if str(code).lower().startswith("it") else "en"
    return _current


def get_lang() -> str:
    return _current


def resolve_lang(cfg_value: str) -> str:
    """'it'/'en' espliciti, altrimenti rilevamento ('auto' o altro)."""
    v = str(cfg_value or "auto").lower()
    if v.startswith("it"):
        return "it"
    if v.startswith("en"):
        return "en"
    return detect_system_lang()


def T(key: str, default: str | None = None, **fmt) -> str:
    """Rende la stringa; fallback it, poi default, poi la chiave stessa."""
    table = STRINGS.get(_current, {})
    text = table.get(
        key, STRINGS["it"].get(key, default if default is not None else key)
    )
    if fmt:
        try:
            return text.format(**fmt)
        except (KeyError, IndexError, ValueError):
            return text
    return text


def key_sections() -> tuple:
    """Sezioni della schermata Tasti nella lingua corrente."""
    return KEY_SECTIONS.get(_current, KEY_SECTIONS["it"])


