def format_date_long(date_str: str) -> str:
    """'2026-09-10' -> 'Giovedì 10 Settembre 2026' / 'Thursday, September 10, 2026'."""
    from datetime import datetime as _dt

    try:
        d = _dt.strptime(date_str, "%Y-%m-%d").date()
    except (ValueError, TypeError):
        return date_str
    if _current == "en":
        return (
            f"{DAYS_LONG['en'][d.weekday()]}, {MONTHS['en'][d.month]} {d.day}, {d.year}"
        )
    try:
        return f"{DAYS_LONG['it'][d.weekday()]} {d.day:02d} {MONTHS['it'][d.month]} {d.year}"
    except IndexError:
        return date_str


